export type LanguageContextType = {
  language: AppLanguage;
  setLanguage: (language: AppLanguage) => void;
  t: (key: string, fallback?: string) => string;
  isRtl: boolean;
  currentLanguageInfo: LanguageInfo;
};

const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

function initialLanguage(): AppLanguage {
  if (typeof window === 'undefined') return 'id';
  try {
    const saved = window.localStorage.getItem(STORAGE_KEY) as AppLanguage | null;
    if (saved && translations[saved]) {
      return saved;
    }
  } catch {}
  return 'id';
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<AppLanguage>(initialLanguage);

  const setLanguage = (next: AppLanguage) => {
    if (!translations[next]) return;
    setLanguageState(next);
    try {
      window.localStorage.setItem(STORAGE_KEY, next);
    } catch {}
  };

  const currentLanguageInfo = useMemo(() => {
    return APP_LANGUAGES.find((item) => item.id === language) || APP_LANGUAGES[0];
  }, [language]);

  const isRtl = currentLanguageInfo.dir === 'rtl';

  useEffect(() => {
    if (typeof document !== 'undefined') {
      document.documentElement.lang = language;
      document.documentElement.dir = isRtl ? 'rtl' : 'ltr';
    }
  }, [language, isRtl]);

  const t = useMemo(() => {
    return (key: string, fallback?: string): string => {
      const dict = translations[language];
      if (dict && dict[key] !== undefined) {
        return dict[key];
      }
      // 1st fallback: Indonesian (default primary language)
      if (translations.id[key] !== undefined) {
        return translations.id[key];
      }
      // 2nd fallback: English
      if (translations.en[key] !== undefined) {
        return translations.en[key];
      }
      // 3rd fallback: explicitly provided fallback or raw key
      return fallback || key;
    };
  }, [language]);

  const value = useMemo(
    () => ({
      language,
      setLanguage,
      t,
      isRtl,
      currentLanguageInfo,
    }),
    [language, t, isRtl, currentLanguageInfo]
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used inside LanguageProvider');
  }
  return context;
}
